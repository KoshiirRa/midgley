/**
 * Edge news article scraper rendering dynamic web content to clean Markdown via Cloudflare Browser Run.
 */
export async function scrapeNewsMarkdownAtEdge(
  env: any,
  url: string,
  options?: { force_refresh?: boolean }
): Promise<NewsScrapeResult> {
  const forceRefresh = Boolean(options?.force_refresh);
  const now = Date.now();
  const maxAgeMs = 24 * 3600 * 1000; // 24-hour TTL for news article snapshots

  if (!url || (!url.startsWith("http://") && !url.startsWith("https://"))) {
    return {
      status: "error",
      provider: "cloudflare_browser_run",
      url: url || "",
      title: "",
      markdown: "",
      cached: false,
      updated_at: new Date().toISOString(),
      error: "Invalid or missing HTTP/HTTPS URL"
    };
  }

  // Simple clean hash for cache key
  const urlKey = "news_md:" + Array.from(new Uint8Array(await crypto.subtle.digest("SHA-256", new TextEncoder().encode(url))))
    .map(b => b.toString(16).padStart(2, "0")).join("").substring(0, 32);

  if (!forceRefresh) {
    const mem = newsMemoryCache.get(urlKey);
    if (mem && (now - mem.cached_at < maxAgeMs)) {
      return { ...mem.data, status: "cached", cached: true };
    }

    if (env?.DB) {
      try {
        const row = await env.DB.prepare("SELECT data, updated_at FROM edge_cache WHERE key = ?").bind(urlKey).first();
        if (row?.data && (now - Number(row.updated_at) < maxAgeMs)) {
          const parsed = JSON.parse(row.data) as NewsScrapeResult;
          parsed.status = "cached";
          parsed.cached = true;
          newsMemoryCache.set(urlKey, { data: parsed, cached_at: Number(row.updated_at) });
          return parsed;
        }
      } catch {
        // ignore cache read notice
      }
    }
  }

  const userAgent = env?.MIDGLEY_AGENT_USER_AGENT || MIDGLEY_AGENT_USER_AGENT;
  const md = await fetchMarkdownViaBrowserRun(env, { url, userAgent });

  if (md && md.trim().length > 0) {
    let title = url;
    const lines = md.split("\n");
    for (const l of lines) {
      const t = l.trim();
      if (t.startsWith("#")) {
        title = t.replace(/^#+\s*/, "").trim();
        break;
      }
    }

    const result: NewsScrapeResult = {
      status: "success",
      provider: "cloudflare_browser_run",
      url,
      title,
      markdown: md,
      cached: false,
      updated_at: new Date().toISOString()
    };

    newsMemoryCache.set(urlKey, { data: result, cached_at: now });
    if (env?.DB) {
      try {
        await env.DB.prepare(
          "INSERT OR REPLACE INTO edge_cache (key, data, updated_at) VALUES (?, ?, ?)"
        ).bind(urlKey, JSON.stringify(result), now).run();
      } catch {
        // ignore cache write notice
      }
    }

    return result;
  }

  return {
    status: "error",
    provider: "cloudflare_browser_run",
    url,
    title: "",
    markdown: "",
    cached: false,
    updated_at: new Date().toISOString(),
    error: "Browser Run returned empty or failed markdown extraction"
  };
}
