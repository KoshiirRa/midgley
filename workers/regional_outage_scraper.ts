/**
 * Cloudflare Edge Scraper for Regional Outages, State Fuel Dashboards & Dynamic News
 * (workers/regional_outage_scraper.ts)
 *
 * Implements serverless headless browser rendering (Issue #640) for:
 * 1. South Coast AQMD (SCAQMD) Rule 1118 Refinery Flare Event Notifications (PADD 5 flaring)
 * 2. NYSERDA Weekly Transportation Fuel Price Survey (PADD 1B regional retail benchmarks)
 * 3. General Edge News-to-Markdown Scraper for incoming URLs with D1 caching
 *
 * Policy User-Agent: MidgleyAgent/1.0 (+https://koshiirra.github.io/midgley/)
 */

import { fetchMarkdownViaBrowserRun } from "./browser_run";

export const MIDGLEY_AGENT_USER_AGENT = "MidgleyAgent/1.0 (+https://koshiirra.github.io/midgley/)";

export interface ScaqmdFlareEvent {
  facility_name: string;
  facility_id?: string;
  city: string;
  start_time: string;
  end_time?: string;
  event_type: "unplanned" | "planned" | "startup_shutdown" | "breakdown" | "unknown";
  clean_gas_scf?: number;
  estimated_sox_lbs?: number;
  status: string;
  raw_description?: string;
}

export interface ScaqmdFlarePayload {
  status: "success" | "cached" | "fallback" | "error";
  source: "CLOUDFLARE_BROWSER_RENDERING" | "EDGE_CACHE" | "FALLBACK";
  as_of: string;
  total_events: number;
  unplanned_events_count: number;
  events: ScaqmdFlareEvent[];
  updated_at: string;
  error?: string;
}

export interface NyserdaRegionPrice {
  region: string;
  regular_gasoline: number;
  diesel?: number;
  as_of?: string;
}

export interface NyserdaWeeklyFuelPayload {
  status: "success" | "cached" | "fallback" | "error";
  source: "CLOUDFLARE_BROWSER_RENDERING" | "EDGE_CACHE" | "FALLBACK";
  as_of: string;
  statewide_average_gasoline: number;
  statewide_average_diesel: number;
  regions: NyserdaRegionPrice[];
  updated_at: string;
  error?: string;
}

export interface NewsScrapeResult {
  status: "success" | "cached" | "error";
  provider: "cloudflare_browser_run";
  url: string;
  title: string;
  markdown: string;
  cached: boolean;
  updated_at: string;
  error?: string;
}

// In-memory caches for worker instances / test runners
let flareMemoryCache: { data: ScaqmdFlarePayload; cached_at: number } | null = null;
let nyserdaMemoryCache: { data: NyserdaWeeklyFuelPayload; cached_at: number } | null = null;
let newsMemoryCache: Map<string, { data: NewsScrapeResult; cached_at: number }> = new Map();

export function clearRegionalScraperMemoryCacheForTesting(): void {
  flareMemoryCache = null;
  nyserdaMemoryCache = null;
  newsMemoryCache.clear();
}

/**
 * Parses markdown output generated by Cloudflare Browser Rendering from SCAQMD Rule 1118 Portal.
 * URL: https://xappp.aqmd.gov/r1118/
 */
export function parseScaqmdFlareMarkdown(markdownText: string): Partial<ScaqmdFlarePayload> {
  const lines = markdownText.split("\n");
  const events: ScaqmdFlareEvent[] = [];
  let inTable = false;
  let headers: string[] = [];
  const asOf = new Date().toISOString().split("T")[0];

  for (const rawLine of lines) {
    const trimmed = rawLine.trim();

    if (trimmed.includes("Rule 1118") || trimmed.includes("Flare Event Notifications") || trimmed.startsWith("|")) {
      if (trimmed.startsWith("|") && (trimmed.toLowerCase().includes("facility") || trimmed.toLowerCase().includes("operator"))) {
        inTable = true;
        headers = trimmed.split("|").map(h => h.trim().toLowerCase()).filter(Boolean);
        continue;
      }
    }

    if (inTable) {
      if (trimmed.startsWith("|--") || trimmed.startsWith("| --") || trimmed.startsWith("|:-")) {
        continue;
      }
      if (trimmed.startsWith("|")) {
        const cols = trimmed.split("|").map(c => c.trim()).slice(1, -1);
        if (cols.length >= 3) {
          const facility = cols[0] || "Unknown Facility";
          const cityOrLocation = cols[1] || "Southern California";
          const rawStart = cols[2] || asOf;
          const rawEnd = cols[3] || "";
          const typeStr = (cols[4] || cols[cols.length - 1] || "").toLowerCase();
          
          let eventType: ScaqmdFlareEvent["event_type"] = "unknown";
          if (typeStr.includes("unplanned") || typeStr.includes("upset") || typeStr.includes("breakdown") || typeStr.includes("trip")) {
            eventType = "unplanned";
          } else if (typeStr.includes("planned") || typeStr.includes("maintenance") || typeStr.includes("turnaround")) {
            eventType = "planned";
          } else if (typeStr.includes("startup") || typeStr.includes("shutdown")) {
            eventType = "startup_shutdown";
          }

          let gasVolume: number | undefined;
          let soxLbs: number | undefined;

          const gasColIdx = headers.findIndex(h => h.includes("gas") || h.includes("scf") || h.includes("volume"));
          const soxColIdx = headers.findIndex(h => h.includes("sox") || h.includes("lb") || h.includes("emission"));

          if (gasColIdx >= 0 && cols[gasColIdx]) {
            const num = parseFloat(cols[gasColIdx].replace(/[,\s]/g, ""));
            if (!isNaN(num)) gasVolume = num;
          }
          if (soxColIdx >= 0 && cols[soxColIdx]) {
            const num = parseFloat(cols[soxColIdx].replace(/[,\s]/g, ""));
            if (!isNaN(num)) soxLbs = num;
          }

          // Fallback heuristic if headers not mapped
          if (!gasVolume || !soxLbs) {
            for (let c = 3; c < cols.length; c++) {
              const valClean = cols[c].replace(/[,\s]/g, "");
              const num = parseFloat(valClean);
              if (!isNaN(num) && num > 0) {
                if (cols[c].toLowerCase().includes("sox") || cols[c].toLowerCase().includes("lb") || (num < 1000 && !soxLbs)) {
                  soxLbs = num;
                } else if (!gasVolume && num > 1000) {
                  gasVolume = num;
                }
              }
            }
          }

          let statusVal = "COMPLETED";
          const statusColIdx = headers.findIndex(h => h.includes("status"));
          if (statusColIdx >= 0 && cols[statusColIdx]) {
            statusVal = cols[statusColIdx].trim().toUpperCase();
          } else if (trimmed.toLowerCase().includes("active") || trimmed.toLowerCase().includes("ongoing")) {
            statusVal = "ACTIVE";
          }

          events.push({
            facility_name: facility,
            city: cityOrLocation,
            start_time: rawStart,
            end_time: rawEnd || undefined,
            event_type: eventType,
            clean_gas_scf: gasVolume,
            estimated_sox_lbs: soxLbs,
            status: statusVal,
            raw_description: trimmed
          });
        }
      } else if (trimmed.length > 0 && !trimmed.startsWith("|") && events.length > 0) {
        // Table boundary reached
        inTable = false;
      }
    }
  }

  const unplannedCount = events.filter(e => e.event_type === "unplanned").length;

  return {
    as_of: asOf,
    total_events: events.length,
    unplanned_events_count: unplannedCount,
    events
  };
}

/**
 * Parses markdown output generated by Cloudflare Browser Rendering from NYSERDA Fuel Price Survey.
 * URL: https://www.nyserda.ny.gov/research-and-development/energy-prices/motor-gasoline/monthly-average-motor-gasoline-prices
 */
export function parseNyserdaFuelMarkdown(markdownText: string): Partial<NyserdaWeeklyFuelPayload> {
  const lines = markdownText.split("\n");
  const regions: NyserdaRegionPrice[] = [];
  let statewideGas = 0;
  let statewideDiesel = 0;
  let asOf = new Date().toISOString().split("T")[0];

  for (const rawLine of lines) {
    const trimmed = rawLine.trim();

    // Look for as_of date stamp in markdown
    const dateMatch = trimmed.match(/(?:as of|week ending|survey date)\s*:?\s*([A-Za-z]+ \d{1,2}, \d{4}|\d{4}-\d{2}-\d{2})/i);
    if (dateMatch) {
      try {
        const parsedDt = new Date(dateMatch[1]);
        if (!isNaN(parsedDt.getTime())) {
          asOf = parsedDt.toISOString().split("T")[0];
        }
      } catch {
        // preserve default asOf
      }
    }

    if (trimmed.startsWith("|")) {
      const cols = trimmed.split("|").map(c => c.trim()).slice(1, -1);
      if (cols.length >= 2) {
        const regName = cols[0];
        const gasPriceMatch = cols[1]?.match(/\$?\s*([1-9]\.\d{2,3})/);
        const dieselMatch = cols[2]?.match(/\$?\s*([1-9]\.\d{2,3})/);

        if (gasPriceMatch) {
          const regGas = parseFloat(gasPriceMatch[1]);
          const diesel = dieselMatch ? parseFloat(dieselMatch[1]) : undefined;

          if (regName.toLowerCase().includes("statewide") || regName.toLowerCase().includes("new york state")) {
            statewideGas = regGas;
            if (diesel) statewideDiesel = diesel;
          } else if (!regName.toLowerCase().includes("region") && !regName.startsWith("-")) {
            regions.push({
              region: regName,
              regular_gasoline: regGas,
              diesel: diesel,
              as_of: asOf
            });
          }
        }
      }
    }
  }

  // If statewide average was not explicitly identified, compute mean of parsed regions
  if (statewideGas === 0 && regions.length > 0) {
    const valid = regions.map(r => r.regular_gasoline).filter(p => p > 1.0 && p < 10.0);
    if (valid.length > 0) {
      statewideGas = Math.round((valid.reduce((a, b) => a + b, 0) / valid.length) * 1000) / 1000;
    }
  }

  return {
    as_of: asOf,
    statewide_average_gasoline: statewideGas,
    statewide_average_diesel: statewideDiesel,
    regions
  };
}

/**
 * Retrieves South Coast AQMD Rule 1118 flare notifications with D1/memory caching.
 */
export async function getScaqmdFlareReports(
  env: any,
  options?: { force_refresh?: boolean }
): Promise<ScaqmdFlarePayload> {
  const forceRefresh = Boolean(options?.force_refresh);
  const now = Date.now();
  const maxAgeMs = 1 * 3600 * 1000; // 1-hour TTL for flare alerts

  if (!forceRefresh && flareMemoryCache && (now - flareMemoryCache.cached_at < maxAgeMs)) {
    return { ...flareMemoryCache.data, status: "cached", source: "EDGE_CACHE" };
  }

  if (!forceRefresh && env?.DB) {
    try {
      const row = await env.DB.prepare(
        "SELECT data, updated_at FROM edge_cache WHERE key = 'scaqmd_rule1118_flares'"
      ).first();
      if (row?.data && (now - Number(row.updated_at) < maxAgeMs)) {
        const parsed = JSON.parse(row.data) as ScaqmdFlarePayload;
        parsed.status = "cached";
        parsed.source = "EDGE_CACHE";
        flareMemoryCache = { data: parsed, cached_at: Number(row.updated_at) };
        return parsed;
      }
    } catch {
      // D1 cache read non-fatal
    }
  }

  const userAgent = env?.MIDGLEY_AGENT_USER_AGENT || MIDGLEY_AGENT_USER_AGENT;
  const targetUrl = "https://xappp.aqmd.gov/r1118/";

  try {
    const md = await fetchMarkdownViaBrowserRun(env, { url: targetUrl, userAgent });
    if (md && md.length > 30) {
      const parsed = parseScaqmdFlareMarkdown(md);
      const payload: ScaqmdFlarePayload = {
        status: "success",
        source: "CLOUDFLARE_BROWSER_RENDERING",
        as_of: parsed.as_of || new Date().toISOString().split("T")[0],
        total_events: parsed.total_events || 0,
        unplanned_events_count: parsed.unplanned_events_count || 0,
        events: parsed.events || [],
        updated_at: new Date().toISOString()
      };

      flareMemoryCache = { data: payload, cached_at: now };
      if (env?.DB) {
        try {
          await env.DB.prepare(
            "INSERT OR REPLACE INTO edge_cache (key, data, updated_at) VALUES ('scaqmd_rule1118_flares', ?, ?)"
          ).bind(JSON.stringify(payload), now).run();
        } catch {
          // ignore cache write notice
        }
      }
      return payload;
    }
  } catch (err: any) {
    console.warn(`[SCAQMD Scraper] Browser rendering notice: ${err.message || String(err)}`);
  }

  // Fallback empty payload
  return {
    status: "fallback",
    source: "FALLBACK",
    as_of: new Date().toISOString().split("T")[0],
    total_events: 0,
    unplanned_events_count: 0,
    events: [],
    updated_at: new Date().toISOString()
  };
}

