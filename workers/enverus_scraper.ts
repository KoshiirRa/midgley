/**
 * Cloudflare Edge Browser Scraper for Enverus / Drillinginfo Daily Rig Count
 * (workers/enverus_scraper.ts)
 *
 * Implements serverless headless browser rendering and markdown extraction (Issue #640)
 * to ingest daily basin-level upstream crude drilling telemetry (Issue #533)
 * without consuming external Firecrawl quota.
 *
 * Policy User-Agent: MidgleyAgent/1.0 (+https://koshiirra.github.io/midgley/)
 */

import { fetchMarkdownViaBrowserRun } from "./browser_run";

export const MIDGLEY_AGENT_USER_AGENT = "MidgleyAgent/1.0 (+https://koshiirra.github.io/midgley/)";

export interface EnverusBasinMetric {
  play: string;
  latest_count: number;
  day_delta: number;
  day_pct: number;
  month_delta: number;
  month_pct: number;
  year_delta: number;
  year_pct: number;
}

export interface EnverusDailyRigCountPayload {
  status: "success" | "cached" | "fallback" | "error";
  source: "CLOUDFLARE_BROWSER_RENDERING" | "ENVERUS_DIRECT_API" | "EDGE_CACHE";
  as_of: string;
  total_rigs: number;
  pct_change_week: number;
  analysis_title?: string;
  analysis_text?: string;
  basins: EnverusBasinMetric[];
  history_dates?: string[];
  updated_at: string;
  error?: string;
}

// In-memory fallback cache for workers when D1 is unavailable or in local test runners
let memoryCache: { data: EnverusDailyRigCountPayload; cached_at: number } | null = null;

export function clearEnverusMemoryCacheForTesting(): void {
  memoryCache = null;
}

/**
 * Parses markdown output generated by Cloudflare Browser Rendering (/markdown quick action)
 * from https://www.enverus.com/dailyrigcount/
 */
export function parseEnverusMarkdown(markdownText: string): Partial<EnverusDailyRigCountPayload> {
  const lines = markdownText.split("\n");
  let analysisTitle: string | undefined;
  const analysisParagraphs: string[] = [];
  let inAnalysis = false;
  let inTable = false;
  const tableLines: string[] = [];

  for (let i = 0; i < lines.length; i++) {
    const rawLine = lines[i];
    const trimmed = rawLine.trim();

    if (trimmed.startsWith("### U.S. drilling activity") || (trimmed.startsWith("### ") && trimmed.toLowerCase().includes("rig"))) {
      if (!trimmed.toLowerCase().includes("basin")) {
        analysisTitle = trimmed.replace(/^###\s*/, "").trim();
        inAnalysis = true;
        continue;
      }
    }

    if (trimmed.startsWith("### Rig Count by Basin") || trimmed.includes("Rig Count by Basin")) {
      inAnalysis = false;
      inTable = true;
      continue;
    }

    if (inAnalysis) {
      if (trimmed.startsWith("Total Orientation Play") || trimmed.startsWith("###")) {
        inAnalysis = false;
      } else if (trimmed.length > 0) {
        analysisParagraphs.push(trimmed);
      }
    }

    if (inTable) {
      if (trimmed.startsWith("|")) {
        tableLines.push(trimmed);
      } else if (tableLines.length > 0 && trimmed.length > 0 && !trimmed.startsWith("|")) {
        // End of table
        inTable = false;
      }
    }
  }

  const basins: EnverusBasinMetric[] = [];
  let totalRigs = 0;
  let historyDates: string[] = [];
  let asOf = new Date().toISOString().split("T")[0];

  if (tableLines.length >= 3) {
    // Header line: | Play | 10/07/26 | ... | 10/14/26 | 1 Day Δ | % | 1 Month Δ | % | 1 Year Δ | % |
    const headerCols = tableLines[0]
      .split("|")
      .map(c => c.trim())
      .filter((_, idx, arr) => idx > 0 && idx < arr.length - 1);

    // Find date columns: matches MM/DD/YY or MM/DD/YYYY
    const dateColIndices: number[] = [];
    headerCols.forEach((col, idx) => {
      if (/^\d{1,2}\/\d{1,2}\/\d{2,4}$/.test(col)) {
        dateColIndices.push(idx);
        historyDates.push(col);
      }
    });

    if (historyDates.length > 0) {
      // Normalize latest date to YYYY-MM-DD
      const latestRaw = historyDates[historyDates.length - 1];
      const parts = latestRaw.split("/");
      if (parts.length === 3) {
        const mm = parts[0].padStart(2, "0");
        const dd = parts[1].padStart(2, "0");
        let yy = parts[2];
        if (yy.length === 2) {
          yy = "20" + yy;
        }
        asOf = `${yy}-${mm}-${dd}`;
      }
    }

    const latestDateIdx = dateColIndices.length > 0 ? dateColIndices[dateColIndices.length - 1] : 1;

    // Parse data rows (skip header and markdown separator)
    for (let r = 2; r < tableLines.length; r++) {
      const cols = tableLines[r]
        .split("|")
        .map(c => c.trim())
        .filter((_, idx, arr) => idx > 0 && idx < arr.length - 1);

      if (cols.length < 2) continue;
      const play = cols[0];
      if (!play || play.toLowerCase() === "play" || play.startsWith("---")) continue;

      const latestCount = parseFloat(cols[latestDateIdx]) || 0;
      // Extract delta columns from end if available
      // Format: [1 Day Δ, %, 1 Month Δ, %, 1 Year Δ, %]
      const deltaCols = cols.slice(latestDateIdx + 1);
      const dayDelta = deltaCols.length >= 1 ? parseFloat(deltaCols[0]) || 0 : 0;
      const dayPct = deltaCols.length >= 2 ? parseFloat(deltaCols[1]) || 0 : 0;
      const monthDelta = deltaCols.length >= 3 ? parseFloat(deltaCols[2]) || 0 : 0;
      const monthPct = deltaCols.length >= 4 ? parseFloat(deltaCols[3]) || 0 : 0;
      const yearDelta = deltaCols.length >= 5 ? parseFloat(deltaCols[4]) || 0 : 0;
      const yearPct = deltaCols.length >= 6 ? parseFloat(deltaCols[5]) || 0 : 0;

      if (play.toLowerCase() === "total") {
        totalRigs = latestCount;
      }

      basins.push({
        play,
        latest_count: latestCount,
        day_delta: dayDelta,
        day_pct: dayPct,
        month_delta: monthDelta,
        month_pct: monthPct,
        year_delta: yearDelta,
        year_pct: yearPct
      });
    }
  }

  // If total not explicitly found, sum non-total plays
  if (totalRigs === 0 && basins.length > 0) {
    const totalRow = basins.find(b => b.play.toLowerCase() === "total");
    if (totalRow) {
      totalRigs = totalRow.latest_count;
    } else {
      totalRigs = basins
        .filter(b => b.play.toLowerCase() !== "other")
        .reduce((sum, b) => sum + b.latest_count, 0);
    }
  }

  return {
    as_of: asOf,
    total_rigs: totalRigs,
    pct_change_week: 0.0,
    analysis_title: analysisTitle,
    analysis_text: analysisParagraphs.join("\n\n"),
    basins,
    history_dates: historyDates
  };
}

/**
 * Executes headless scraping via Cloudflare Browser Run unified library
 */
export async function fetchViaCloudflareBrowser(env: any, userAgent: string): Promise<string | null> {
  return await fetchMarkdownViaBrowserRun(env, {
    url: "https://www.enverus.com/dailyrigcount/",
    userAgent
  });
}

/**
 * Direct REST fallback querying Drillinginfo service endpoints with policy user-agent
 */
export async function fetchViaDirectDrillinginfoAPI(userAgent: string): Promise<EnverusDailyRigCountPayload | null> {
  try {
    const headers = {
      "User-Agent": userAgent,
      "Accept": "application/json"
    };

    const [overTableRes, countRes, changeRes, analysisRes, lastUpdateRes] = await Promise.all([
      fetch("https://app.drillinginfo.com/drcservice/api/OverTable", { headers }),
      fetch("https://app.drillinginfo.com/drcservice/api/Count", { headers }).catch(() => null),
      fetch("https://app.drillinginfo.com/drcservice/api/Change/week", { headers }).catch(() => null),
      fetch("https://app.drillinginfo.com/drcservice/api/analysis", { headers }).catch(() => null),
      fetch("https://app.drillinginfo.com/drcservice/api/lastupdate", { headers }).catch(() => null)
    ]);

    if (!overTableRes || overTableRes.status !== 200) {
      return null;
    }

    const tableJson: any = await overTableRes.json();
    const countVal: number = countRes && countRes.status === 200 ? parseFloat(await countRes.text()) || 0 : 0;
    const changeVal: number = changeRes && changeRes.status === 200 ? parseFloat(await changeRes.text()) || 0 : 0;
    
    let analysisData: { text?: string; date?: string } = {};
    if (analysisRes && analysisRes.status === 200) {
      try {
        analysisData = await analysisRes.json();
      } catch {
        // ignore json parse error
      }
    }

    let asOf = new Date().toISOString().split("T")[0];
    if (lastUpdateRes && lastUpdateRes.status === 200) {
      const rawDt = (await lastUpdateRes.text()).replace(/"/g, "").trim();
      if (/^\d{4}-\d{2}-\d{2}$/.test(rawDt)) {
        asOf = rawDt;
      }
    }

    const basins: EnverusBasinMetric[] = [];
    let totalRigs = countVal;

    if (Array.isArray(tableJson.data)) {
      for (const item of tableJson.data) {
        const play = item.play || "";
        const daDelta = typeof item.da_delta === "number" ? item.da_delta : parseFloat(item.da_delta) || 0;
        const daPct = typeof item.da_pct === "number" ? item.da_pct : parseFloat(item.da_pct) || 0;
        const maDelta = typeof item.ma_delta === "number" ? item.ma_delta : parseFloat(item.ma_delta) || 0;
        const maPct = typeof item.ma_pct === "number" ? item.ma_pct : parseFloat(item.ma_pct) || 0;
        const yaDelta = typeof item.ya_delta === "number" ? item.ya_delta : parseFloat(item.ya_delta) || 0;
        const yaPct = typeof item.ya_pct === "number" ? item.ya_pct : parseFloat(item.ya_pct) || 0;

        // Find latest count from item keys (date pattern MM/DD/YY)
        let latestCount = 0;
        const dateKeys = Object.keys(item).filter(k => /^\d{1,2}\/\d{1,2}\/\d{2,4}$/.test(k));
        if (dateKeys.length > 0) {
          const lastKey = dateKeys[dateKeys.length - 1];
          latestCount = typeof item[lastKey] === "number" ? item[lastKey] : parseFloat(item[lastKey]) || 0;
        }

        if (play.toLowerCase() === "total" && totalRigs === 0) {
          totalRigs = latestCount;
        }

        basins.push({
          play,
          latest_count: latestCount,
          day_delta: daDelta,
          day_pct: daPct,
          month_delta: maDelta,
          month_pct: maPct,
          year_delta: yaDelta,
          year_pct: yaPct
        });
      }
    }

    return {
      status: "success",
      source: "ENVERUS_DIRECT_API",
      as_of: asOf,
      total_rigs: totalRigs,
      pct_change_week: changeVal,
      analysis_title: "Enverus Foundations Weekly Activity",
      analysis_text: analysisData.text || "",
      basins,
      updated_at: new Date().toISOString()
    };
  } catch (err: any) {
    console.warn(`[Enverus Direct API] Fetch failed: ${err.message || String(err)}`);
    return null;
  }
}

/**
 * Retrieves the latest daily rig count and basin breakdown with edge caching & failover
 */
export async function getEnverusDailyRigCount(
  env: any,
  options?: { force_refresh?: boolean }
): Promise<EnverusDailyRigCountPayload> {
  const forceRefresh = Boolean(options?.force_refresh);
  const now = Date.now();
  const maxAgeMs = 12 * 3600 * 1000; // 12 hours TTL

  // 1. Check in-memory / test cache
  if (!forceRefresh && memoryCache && (now - memoryCache.cached_at < maxAgeMs)) {
    return { ...memoryCache.data, status: "cached", source: "EDGE_CACHE" };
  }

  // 2. Check D1 cache if available
  if (!forceRefresh && env?.DB) {
    try {
      const row = await env.DB.prepare(
        "SELECT data, updated_at FROM edge_cache WHERE key = 'enverus_daily_rig_count'"
      ).first();
      if (row?.data && (now - Number(row.updated_at) < maxAgeMs)) {
        const parsed = JSON.parse(row.data) as EnverusDailyRigCountPayload;
        parsed.status = "cached";
        parsed.source = "EDGE_CACHE";
        memoryCache = { data: parsed, cached_at: Number(row.updated_at) };
        return parsed;
      }
    } catch {
      // Ignore D1 cache read error (table might not exist in dev)
    }
  }

  const userAgent = env?.MIDGLEY_AGENT_USER_AGENT || MIDGLEY_AGENT_USER_AGENT;

  // 3. Try Cloudflare Browser Rendering (Issue #640)
  const browserMarkdown = await fetchViaCloudflareBrowser(env, userAgent);
  if (browserMarkdown && browserMarkdown.length > 50) {
    const parsed = parseEnverusMarkdown(browserMarkdown);
    if (parsed.total_rigs && parsed.total_rigs > 0) {
      const payload: EnverusDailyRigCountPayload = {
        status: "success",
        source: "CLOUDFLARE_BROWSER_RENDERING",
        as_of: parsed.as_of || new Date().toISOString().split("T")[0],
        total_rigs: parsed.total_rigs,
        pct_change_week: parsed.pct_change_week || 0.0,
        analysis_title: parsed.analysis_title,
        analysis_text: parsed.analysis_text,
        basins: parsed.basins || [],
        history_dates: parsed.history_dates,
        updated_at: new Date().toISOString()
      };

      // Persist to memory and D1 cache
      memoryCache = { data: payload, cached_at: now };
      if (env?.DB) {
        try {
          await env.DB.prepare(
            "INSERT OR REPLACE INTO edge_cache (key, data, updated_at) VALUES ('enverus_daily_rig_count', ?, ?)"
          ).bind(JSON.stringify(payload), now).run();
        } catch {
          // ignore cache write error
        }
      }

      return payload;
    }
  }

  // 4. Fast-path fallback to direct Drillinginfo REST API (Issue #533)
  const apiPayload = await fetchViaDirectDrillinginfoAPI(userAgent);
  if (apiPayload && apiPayload.total_rigs > 0) {
    memoryCache = { data: apiPayload, cached_at: now };
    if (env?.DB) {
      try {
        await env.DB.prepare(
          "INSERT OR REPLACE INTO edge_cache (key, data, updated_at) VALUES ('enverus_daily_rig_count', ?, ?)"
        ).bind(JSON.stringify(apiPayload), now).run();
      } catch {
        // ignore cache write error
      }
    }
    return apiPayload;
  }

  // 5. If everything failed, return stale cache if available, or structured error
  if (memoryCache) {
    return { ...memoryCache.data, status: "fallback", source: "EDGE_CACHE" };
  }

  return {
    status: "error",
    source: "CLOUDFLARE_BROWSER_RENDERING",
    as_of: new Date().toISOString().split("T")[0],
    total_rigs: 0,
    pct_change_week: 0.0,
    basins: [],
    updated_at: new Date().toISOString(),
    error: "Unable to retrieve Enverus rig counts from Cloudflare Browser Rendering or Drillinginfo API."
  };
}
